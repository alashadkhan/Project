import { markdownSafe } from "@/lib/security/sanitize";
import type { ResearchReport, Verdict } from "@/lib/types";

const VERDICT_LABEL: Record<Verdict, string> = {
  supported: "Supported",
  contradicted: "Contradicted",
  mixed: "Mixed evidence",
  insufficient_evidence: "Insufficient evidence",
};

/**
 * Builds a portable Markdown report. Pure and unit-tested so exports never
 * drift from what the UI shows.
 */
export function reportToMarkdown(report: ResearchReport): string {
  const lines: string[] = [];

  lines.push(`# Verification report: ${markdownSafe(report.claim)}`);
  lines.push("");
  lines.push(`- **Verdict:** ${VERDICT_LABEL[report.verdict]}`);
  lines.push(`- **Confidence:** ${Math.round(report.confidence * 100)}%`);
  lines.push(`- **Generated:** ${report.createdAt}`);
  lines.push(`- **Model:** ${markdownSafe(report.model)}`);
  lines.push(`- **Report id:** ${report.id}`);
  lines.push("");
  lines.push("## Summary");
  lines.push("");
  lines.push(markdownSafe(report.summary));
  lines.push("");

  if (report.conflicts.length > 0) {
    lines.push("## Conflicting evidence");
    lines.push("");
    for (const conflict of report.conflicts) {
      lines.push(`- **${markdownSafe(conflict.topic)}** — ${markdownSafe(conflict.description)}`);
    }
    lines.push("");
  }

  lines.push("## Claim-by-claim");
  lines.push("");
  for (const claim of report.claims) {
    lines.push(`### ${claim.id} · ${claim.stance} · ${Math.round(claim.confidence * 100)}%`);
    lines.push("");
    lines.push(markdownSafe(claim.text));
    lines.push("");
    lines.push(`_${markdownSafe(claim.rationale)}_`);
    lines.push("");
    for (const ref of claim.evidence) {
      const source = report.sources.find((item) => item.id === ref.sourceId);
      lines.push(`> ${markdownSafe(ref.quote)}`);
      lines.push("");
      lines.push(source ? `Source: [${ref.sourceId}] ${source.url}` : `Source: ${ref.sourceId} (missing)`);
      lines.push("");
    }
  }

  lines.push("## Sources");
  lines.push("");
  for (const source of report.sources) {
    lines.push(`- [${source.id}] [${markdownSafe(source.title)}](${source.url}) — ${source.publisher}`);
  }
  lines.push("");

  lines.push("## Limitations");
  lines.push("");
  for (const item of report.limitations) lines.push(`- ${markdownSafe(item)}`);
  lines.push("");

  lines.push("## Next steps");
  lines.push("");
  for (const item of report.nextSteps) lines.push(`- ${markdownSafe(item)}`);
  lines.push("");

  lines.push("---");
  lines.push("Generated by Veritas — multi-agent fact-checking with an evidence trail.");

  return lines.join("\n");
}
